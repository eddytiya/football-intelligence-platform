from pathlib import Path
import json
import numpy as np
import pandas as pd
from sklearn.feature_selection import VarianceThreshold
from sklearn.ensemble import RandomForestClassifier

class FeatureSelector:
    """
    Machine Learning Feature Selection Pipeline.

    Responsibilities
    ----------------
    - Load processed datasets
    - Separate features and target
    - Remove constant features
    - Remove low variance features
    - Remove highly correlated features
    - Rank feature importance
    - Select best features
    - Save selected datasets
    """

    def __init__(self):
        """
        Initialize project paths and datasets.
        """

        # ======================================================
        # Project Paths
        # ======================================================

        self.base_path = Path(__file__).resolve().parents[3]

        self.processed_path = (
            self.base_path / "data" / "processed"
        )

        self.metadata_path = (
            self.base_path / "models" / "metadata"
        )

        self.metadata_path.mkdir(
            parents=True,
            exist_ok=True,
        )

        # ======================================================
        # Input Dataset Paths
        # ======================================================

        self.train_path = (
            self.processed_path / "train_processed.csv"
        )

        self.validation_path = (
            self.processed_path / "validation_processed.csv"
        )

        self.test_path = (
            self.processed_path / "test_processed.csv"
        )

        # ======================================================
        # Output Dataset Paths
        # ======================================================

        self.selected_train_path = (
            self.processed_path / "train_selected.csv"
        )

        self.selected_validation_path = (
            self.processed_path / "validation_selected.csv"
        )

        self.selected_test_path = (
            self.processed_path / "test_selected.csv"
        )

        # ======================================================
        # Metadata
        # ======================================================

        self.feature_importance_path = (
            self.metadata_path / "feature_importance.csv"
        )

        self.selected_features_path = (
            self.metadata_path / "selected_features.json"
        )

        # ======================================================
        # Dataset Containers
        # ======================================================

        self.train_dataset = pd.DataFrame()

        self.validation_dataset = pd.DataFrame()

        self.test_dataset = pd.DataFrame()

        # ======================================================
        # Feature / Target
        # ======================================================

        self.target_column = "match_result"
        # ======================================================
        # Feature Selection Configuration
        # ======================================================

        # Threshold for removing low variance features
        self.low_variance_threshold = 0.01

        # Threshold for removing highly correlated features
        self.correlation_threshold = 0.95

        # Random seed for reproducibility
        self.random_state = 42

        # Percentage of top features to keep
        self.top_feature_percentage = 0.80

        self.X_train = pd.DataFrame()

        self.X_validation = pd.DataFrame()

        self.X_test = pd.DataFrame()

        self.y_train = pd.Series(dtype="int64")

        self.y_validation = pd.Series(dtype="int64")

        self.y_test = pd.Series(dtype="int64")

                # ======================================================
        # Feature Tracking
        # ======================================================

        self.constant_features = []

        self.low_variance_features = []

        self.correlated_features = []

        self.selected_features = []
                # ======================================================
        # Feature Importance
        # ======================================================

        self.feature_importance_model = None

        self.feature_importance = pd.DataFrame()

            # ==========================================================
    # STEP 1: Load Processed Datasets
    # ==========================================================

    def load_processed_datasets(self) -> None:
        """
        Load the processed datasets generated by preprocessing.py.
        """

        print("=" * 70)
        print("Football Intelligence Platform")
        print("Machine Learning - Feature Selection")
        print("=" * 70)

        print("\nLoading processed datasets...")

        self.train_dataset = pd.read_csv(
            self.train_path
        )

        self.validation_dataset = pd.read_csv(
            self.validation_path
        )

        self.test_dataset = pd.read_csv(
            self.test_path
        )

        print("✓ Processed datasets loaded successfully.\n")

        print("Dataset Shapes")
        print("-" * 70)

        print(f"Training   : {self.train_dataset.shape}")

        print(f"Validation : {self.validation_dataset.shape}")

        print(f"Test       : {self.test_dataset.shape}")

        # ==========================================================
    # STEP 2: Separate Features and Target
    # ==========================================================

    def separate_features_and_target(self) -> None:
        """
        Separate features and target column.
        """

        print("\n" + "=" * 70)
        print("SEPARATE FEATURES AND TARGET")
        print("=" * 70)

        self.X_train = self.train_dataset.drop(
            columns=self.target_column
        )

        self.y_train = self.train_dataset[
            self.target_column
        ]

        self.X_validation = self.validation_dataset.drop(
            columns=self.target_column
        )

        self.y_validation = self.validation_dataset[
            self.target_column
        ]

        self.X_test = self.test_dataset.drop(
            columns=self.target_column
        )

        self.y_test = self.test_dataset[
            self.target_column
        ]

        print("✓ Feature matrices created.\n")

        print(f"X_train      : {self.X_train.shape}")
        print(f"X_validation : {self.X_validation.shape}")
        print(f"X_test       : {self.X_test.shape}")

        # ==========================================================
    # STEP 3: Inspect Features
    # ==========================================================

    def inspect_features(self) -> None:
        """
        Display basic information about the feature matrix.
        """

        print("\n" + "=" * 70)
        print("FEATURE INSPECTION")
        print("=" * 70)

        print(f"Total Features : {len(self.X_train.columns)}")

        print("\nFirst 10 Features")
        print("-" * 70)

        for index, column in enumerate(
            self.X_train.columns[:10],
            start=1,
        ):
            print(f"{index:2}. {column}")

        print("\nLast 10 Features")
        print("-" * 70)

        total = len(self.X_train.columns)

        for index, column in enumerate(
            self.X_train.columns[-10:],
            start=total - 9,
        ):
            print(f"{index:3}. {column}")

            # ==========================================================
    # STEP 4: Remove Constant Features
    # ==========================================================

    def remove_constant_features(self) -> None:
        """
        Remove features with zero variance.
        """

        print("\n" + "=" * 70)
        print("REMOVE CONSTANT FEATURES")
        print("=" * 70)

        selector = VarianceThreshold(
            threshold=0.0
        )

        selector.fit(self.X_train)

        selected_columns = self.X_train.columns[
            selector.get_support()
        ]

        removed_columns = self.X_train.columns[
            ~selector.get_support()
        ].tolist()

        # Store removed features
        self.constant_features = removed_columns

        self.X_train = self.X_train[selected_columns]

        self.X_validation = self.X_validation[
            selected_columns
        ]

        self.X_test = self.X_test[
            selected_columns
        ]

        print(
            f"Removed Constant Features : {len(self.constant_features)}"
        )

        print(
            f"Remaining Features        : {self.X_train.shape[1]}"
        )

        if self.constant_features:

            print("\nRemoved Columns")
            print("-" * 70)

            for column in self.constant_features:
                print(column)

        else:

            print("\n✓ No constant features found.")

            # ==========================================================
    # STEP 5: Remove Low Variance Features
    # ==========================================================

    def remove_low_variance_features(self) -> None:
        """
        Remove features with low variance.
        """

        print("\n" + "=" * 70)
        print("REMOVE LOW VARIANCE FEATURES")
        print("=" * 70)

        selector = VarianceThreshold(
            threshold=self.low_variance_threshold
        )

        selector.fit(self.X_train)

        selected_columns = self.X_train.columns[
            selector.get_support()
        ]

        removed_columns = self.X_train.columns[
            ~selector.get_support()
        ].tolist()

        # Store removed features
        self.low_variance_features = removed_columns

        self.X_train = self.X_train[selected_columns]

        self.X_validation = self.X_validation[
            selected_columns
        ]

        self.X_test = self.X_test[
            selected_columns
        ]

        print(
            f"Threshold : {self.low_variance_threshold}"
        )

        print(
            f"Removed Features : {len(self.low_variance_features)}"
        )

        print(
            f"Remaining Features : {self.X_train.shape[1]}"
        )

        if self.low_variance_features:

            print("\nRemoved Columns")
            print("-" * 70)

            for column in self.low_variance_features:
                print(column)

        else:

            print("\n✓ No low variance features found.")

        # ==========================================================
    # STEP 6: Correlation Analysis
    # ==========================================================

    def correlation_analysis(self) -> None:
        """
        Identify highly correlated features.
        """

        print("\n" + "=" * 70)
        print("CORRELATION ANALYSIS")
        print("=" * 70)

        print(
            f"Correlation Threshold : {self.correlation_threshold}"
        )

        # ------------------------------------------------------
        # Compute absolute correlation matrix
        # ------------------------------------------------------

        correlation_matrix = (
            self.X_train
            .corr()
            .abs()
        )

        

        # ------------------------------------------------------
        # Keep only the upper triangle of the matrix
        # ------------------------------------------------------

        upper_triangle = correlation_matrix.where(

            np.triu(

                np.ones(
                    correlation_matrix.shape,
                    dtype=bool,
                ),

                k=1,

            )

        )

        # ------------------------------------------------------
        # Identify correlated features
        # ------------------------------------------------------

        self.correlated_features = [
            column
            for column in upper_triangle.columns
            if any(
                upper_triangle[column]
                > self.correlation_threshold
            )
        ]

        print(
            f"Highly Correlated Features : {len(self.correlated_features)}"
        )

        if self.correlated_features:

            print("\nFeatures to Remove")

            print("-" * 70)

            for feature in self.correlated_features:
                print(feature)

        else:

            print("\n✓ No highly correlated features found.")

        # ==========================================================
    # STEP 7: Remove Correlated Features
    # ==========================================================

    def remove_correlated_features(self) -> None:
        """
        Remove highly correlated features from all datasets.
        """

        print("\n" + "=" * 70)
        print("REMOVE CORRELATED FEATURES")
        print("=" * 70)

        if not self.correlated_features:

            print("✓ No correlated features to remove.")

            return

        self.X_train = self.X_train.drop(
            columns=self.correlated_features
        )

        self.X_validation = self.X_validation.drop(
            columns=self.correlated_features
        )

        self.X_test = self.X_test.drop(
            columns=self.correlated_features
        )

        print(
            f"Removed Features : {len(self.correlated_features)}"
        )

        print(
            f"Remaining Features : {self.X_train.shape[1]}"
        )

        print("\nDatasets Updated")

        print("-" * 70)

        print(f"Train      : {self.X_train.shape}")

        print(f"Validation : {self.X_validation.shape}")

        print(f"Test       : {self.X_test.shape}")

        # ==========================================================
    # STEP 8: Train Feature Importance Model
    # ==========================================================

    def train_feature_importance_model(self) -> None:
        """
        Train a Random Forest model to estimate feature importance.
        """

        print("\n" + "=" * 70)
        print("TRAIN FEATURE IMPORTANCE MODEL")
        print("=" * 70)

        self.feature_importance_model = RandomForestClassifier(

            n_estimators=500,

            random_state=self.random_state,

            n_jobs=-1,

        )

        self.feature_importance_model.fit(

            self.X_train,

            self.y_train,

        )

        print("✓ Random Forest trained successfully.")

        print(
            f"Training Samples : {len(self.X_train)}"
        )

        print(
            f"Features Used : {self.X_train.shape[1]}"
        )

        # ==========================================================
    # STEP 9: Calculate Feature Importance
    # ==========================================================

    def calculate_feature_importance(self) -> None:
        """
        Calculate and rank feature importance scores.
        """

        print("\n" + "=" * 70)
        print("FEATURE IMPORTANCE")
        print("=" * 70)

        self.feature_importance = pd.DataFrame(

            {

                "feature": self.X_train.columns,

                "importance": self.feature_importance_model.feature_importances_,

            }

        )

        self.feature_importance = (

            self.feature_importance

            .sort_values(

                by="importance",

                ascending=False,

            )

            .reset_index(drop=True)

        )

        print(
            f"Total Ranked Features : {len(self.feature_importance)}"
        )

        print("\nTop 20 Most Important Features")

        print("-" * 70)

        print(

            self.feature_importance.head(20)

        )

        # ==========================================================
    # STEP 10: Select Top Features
    # ==========================================================

    def select_top_features(self) -> None:
        """
        Select the top features based on feature importance.
        """

        print("\n" + "=" * 70)
        print("SELECT TOP FEATURES")
        print("=" * 70)

        number_of_features = int(

            len(self.feature_importance)

            * self.top_feature_percentage

        )

        self.selected_features = (

            self.feature_importance

            .head(number_of_features)["feature"]

            .tolist()

        )

        self.X_train = self.X_train[
            self.selected_features
        ]

        self.X_validation = self.X_validation[
            self.selected_features
        ]

        self.X_test = self.X_test[
            self.selected_features
        ]

        print(
            f"Selected Features : {len(self.selected_features)}"
        )

        print(
            f"Removed Features : {122 - len(self.selected_features)}"
        )

        print(
            f"Train Shape : {self.X_train.shape}"
        )

        print(
            f"Validation Shape : {self.X_validation.shape}"
        )

        print(
            f"Test Shape : {self.X_test.shape}"
        )


        # ==========================================================
    # STEP 11: Save Selected Datasets
    # ==========================================================

    def save_selected_datasets(self) -> None:
        """
        Save the selected datasets.
        """

        print("\n" + "=" * 70)
        print("SAVE SELECTED DATASETS")
        print("=" * 70)

        train_dataset = self.X_train.copy()
        train_dataset[self.target_column] = self.y_train

        validation_dataset = self.X_validation.copy()
        validation_dataset[self.target_column] = self.y_validation

        test_dataset = self.X_test.copy()
        test_dataset[self.target_column] = self.y_test

        train_dataset.to_csv(
            self.selected_train_path,
            index=False,
        )

        validation_dataset.to_csv(
            self.selected_validation_path,
            index=False,
        )

        test_dataset.to_csv(
            self.selected_test_path,
            index=False,
        )

        print("✓ Selected datasets saved successfully.")

        # ==========================================================
    # STEP 12: Save Feature Metadata
    # ==========================================================

    def save_feature_metadata(self) -> None:
        """
        Save feature importance and selected feature metadata.
        """

        print("\n" + "=" * 70)
        print("SAVE FEATURE METADATA")
        print("=" * 70)

        self.feature_importance.to_csv(
            self.feature_importance_path,
            index=False,
        )

        with open(
            self.selected_features_path,
            "w",
            encoding="utf-8",
        ) as file:

            json.dump(

                self.selected_features,

                file,

                indent=4,

            )

        print("✓ Feature importance saved.")
        print("✓ Selected feature list saved.")

    

    def run(self):

        self.load_processed_datasets()

        self.separate_features_and_target()

        self.inspect_features()

        self.remove_constant_features()

        self.remove_low_variance_features()

        self.correlation_analysis()

        self.remove_correlated_features()

        self.train_feature_importance_model()

        self.calculate_feature_importance()

        self.select_top_features()

        self.save_selected_datasets()

        self.save_feature_metadata()

if __name__ == "__main__":

    selector = FeatureSelector()

    selector.run()