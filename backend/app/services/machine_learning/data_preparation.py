"""
Machine Learning Data Preparation

This module prepares the football dataset for machine learning.

Responsibilities
----------------
- Load the dataset
- Inspect the dataset
- Create the target variable
- Remove leakage columns
- Detect feature types
- Handle missing values
- Perform a chronological train/validation/test split
- Save processed datasets

Author: Aditya Pathak
Project: Football Intelligence Platform
"""

from pathlib import Path

import pandas as pd


class DataPreparation:
    """
    Prepares the football dataset for machine learning.

    This class performs every step required before model training.
    Each method represents one logical preprocessing step,
    making the code easy to understand, maintain, and extend.
    """

    def __init__(self) -> None:
        """
        Initialize project paths.

        Project Structure
        -----------------
        backend/
        ├── data/
        │   ├── raw/
        │   ├── processed/
        │   └── splits/
        """

        # ==========================================================
        # Project Paths
        # ==========================================================

        # backend/
        self.base_path = Path(__file__).resolve().parents[3]

        # Dataset folders
        self.raw_path = self.base_path / "data" / "raw"
        self.processed_path = self.base_path / "data" / "processed"
        self.splits_path = self.base_path / "data" / "splits"

        # ==========================================================
        # Dataset File
        # ==========================================================

        # Load the latest dataset generated by DatasetBuilder
        self.dataset_path = self.processed_path / "football_dataset.csv"

        # ==========================================================
        # DataFrame
        # ==========================================================

        self.dataset: pd.DataFrame = pd.DataFrame()

        # ==========================================================
        # Feature Groups
        # ==========================================================

        self.date_columns = []
        self.integer_columns = []
        self.float_columns = []
        self.object_columns = []

        # ==========================================================
        # Target Column
        # ==========================================================

        self.target_column = "match_result"

        # ==========================================================
        # Leakage Columns
        # ==========================================================

        self.leakage_columns = []

        # ==========================================================
        # String Form Columns
        # ==========================================================

        self.string_form_columns = [
            "home_form",
            "home_form_only",
            "away_form",
            "away_form_only",
            "h2h_form",
        ]

        # ==========================================================
        # Dataset Splits
        # ==========================================================

        self.train_dataset = pd.DataFrame()
        self.validation_dataset = pd.DataFrame()
        self.test_dataset = pd.DataFrame()

        # ==========================================================
        # Split Ratios
        # ==========================================================

        self.train_ratio = 0.70
        self.validation_ratio = 0.15
        self.test_ratio = 0.15

        print("=" * 70)
        print("Football Intelligence Platform")
        print("Machine Learning - Data Preparation")
        print("=" * 70)
        print(f"Project Path : {self.base_path}")
        print(f"Dataset Path : {self.dataset_path}")
        print("=" * 70)

    # ==========================================================
    # STEP 1: Load Dataset
    # ==========================================================

    def load_dataset(self) -> pd.DataFrame:
        """
        Load the raw football dataset.

        Returns
        -------
        pd.DataFrame
            Loaded dataset.

        Raises
        ------
        FileNotFoundError
            If the dataset does not exist.
        """

        print("\n[STEP 1] Loading dataset...")

        if not self.dataset_path.exists():
            raise FileNotFoundError(
                f"Dataset not found:\n{self.dataset_path}"
            )

        self.dataset = pd.read_csv(self.dataset_path)

        print("✓ Dataset loaded successfully.")
        print(f"Rows    : {len(self.dataset):,}")
        print(f"Columns : {self.dataset.shape[1]}")

        return self.dataset

    # ==========================================================
    # STEP 2: Display Dataset Shape
    # ==========================================================

    def display_shape(self) -> None:
        """
        Display the number of rows and columns.
        """

        print("\n" + "=" * 70)
        print("DATASET SHAPE")
        print("=" * 70)

        rows, columns = self.dataset.shape

        print(f"Rows    : {rows:,}")
        print(f"Columns : {columns}")

    # ==========================================================
    # STEP 3: Display Dataset Columns
    # ==========================================================

    def display_columns(self) -> None:
        """
        Display all dataset columns.
        """

        print("\n" + "=" * 70)
        print("DATASET COLUMNS")
        print("=" * 70)

        for index, column in enumerate(self.dataset.columns, start=1):
            print(f"{index:>3}. {column}")

    # ==========================================================
    # STEP 4: Display Data Types
    # ==========================================================

    def display_data_types(self) -> None:
        """
        Display the data type of every column.
        """

        print("\n" + "=" * 70)
        print("DATA TYPES")
        print("=" * 70)

        print(self.dataset.dtypes)

    # ==========================================================
    # STEP 5: Display Memory Usage
    # ==========================================================

    def display_memory_usage(self) -> None:
        """
        Display dataset memory usage.
        """

        print("\n" + "=" * 70)
        print("MEMORY USAGE")
        print("=" * 70)

        memory = self.dataset.memory_usage(deep=True).sum()

        print(f"Memory Usage : {memory / 1024:.2f} KB")


    # ==========================================================
    # STEP 6: Display Sample Rows
    # ==========================================================

    def display_sample_rows(self, rows: int = 5) -> pd.DataFrame:
        """
        Display the first few rows of the dataset.

        Parameters
        ----------
        rows : int, default=5
            Number of rows to display.

        Returns
        -------
        pd.DataFrame
            Sample rows from the dataset.
        """

        print("\n" + "=" * 70)
        print("SAMPLE DATA")
        print("=" * 70)

        sample = self.dataset.head(rows)

        print(sample)

        return sample

    # ==========================================================
    # STEP 7: Display Missing Values
    # ==========================================================

    def display_missing_values(self) -> pd.DataFrame:
        """
        Display missing value statistics for every column.

        Returns
        -------
        pd.DataFrame
            DataFrame containing missing value information.
        """

        print("\n" + "=" * 70)
        print("MISSING VALUES")
        print("=" * 70)

        # Count missing values
        missing_count = self.dataset.isnull().sum()

        # Calculate percentages
        missing_percentage = (
            missing_count / len(self.dataset)
        ) * 100

        # Build summary table
        missing_summary = pd.DataFrame(
            {
                "Missing Count": missing_count,
                "Missing Percentage": missing_percentage.round(2)
            }
        )

        # Keep only columns with missing values
        missing_summary = missing_summary[
            missing_summary["Missing Count"] > 0
        ]

        # Sort by highest percentage
        missing_summary = missing_summary.sort_values(
            by="Missing Percentage",
            ascending=False
        )

        if missing_summary.empty:
            print("✓ No missing values found in the dataset.")
        else:
            print(missing_summary)

        return missing_summary

    # ==========================================================
    # STEP 8: Display Duplicate Rows
    # ==========================================================

    def display_duplicate_rows(self) -> pd.DataFrame:
        """
        Display duplicate rows in the dataset.

        Returns
        -------
        pd.DataFrame
            Duplicate rows.
        """

        print("\n" + "=" * 70)
        print("DUPLICATE ROWS")
        print("=" * 70)

        duplicates = self.dataset[self.dataset.duplicated()]

        duplicate_count = len(duplicates)

        print(f"Duplicate Rows : {duplicate_count}")

        if duplicate_count > 0:
            print("\nDuplicate Records:")
            print(duplicates)
        else:
            print("✓ No duplicate rows found.")

        return duplicates

    # ==========================================================
    # STEP 9: Display Numerical Summary
    # ==========================================================

    def display_numerical_summary(self) -> pd.DataFrame:
        """
        Display descriptive statistics for all numerical columns.

        Returns
        -------
        pd.DataFrame
            Summary statistics of all numerical features.
        """

        print("\n" + "=" * 70)
        print("NUMERICAL SUMMARY")
        print("=" * 70)

        numerical_summary = self.dataset.describe().transpose()

        print(numerical_summary)

        return numerical_summary


    # ==========================================================
    # STEP 10: Display Feature Type Summary
    # ==========================================================

    def display_feature_type_summary(self) -> dict:
        """
        Classify dataset columns by data type.

        Returns
        -------
        dict
            Dictionary containing grouped feature names.
        """

        print("\n" + "=" * 70)
        print("FEATURE TYPE SUMMARY")
        print("=" * 70)

        # Reset lists
        self.date_columns = []
        self.integer_columns = []
        self.float_columns = []
        self.object_columns = []

        # Detect feature types
        for column in self.dataset.columns:

            dtype = self.dataset[column].dtype

            if column == "match_date":
                self.date_columns.append(column)

            elif str(dtype).startswith("int"):
                self.integer_columns.append(column)

            elif str(dtype).startswith("float"):
                self.float_columns.append(column)

            else:
                self.object_columns.append(column)

        print(f"Date Columns    : {len(self.date_columns)}")
        print(f"Integer Columns : {len(self.integer_columns)}")
        print(f"Float Columns   : {len(self.float_columns)}")
        print(f"Object Columns  : {len(self.object_columns)}")

        print("\nDate Columns")
        print("-" * 70)
        for column in self.date_columns:
            print(column)

        print("\nObject Columns")
        print("-" * 70)
        for column in self.object_columns:
            print(column)

        return {
            "date_columns": self.date_columns,
            "integer_columns": self.integer_columns,
            "float_columns": self.float_columns,
            "object_columns": self.object_columns,
        }

    # ==========================================================
    # STEP 11: Convert Match Date
    # ==========================================================

    def convert_match_date(self) -> None:
        """
        Convert the match_date column to datetime.
        """

        print("\n" + "=" * 70)
        print("CONVERT MATCH DATE")
        print("=" * 70)

        self.dataset["match_date"] = pd.to_datetime(
            self.dataset["match_date"],
            errors="coerce"
        )

        # Fill missing match_date using match_id order
        self.dataset["match_date"] = (
            self.dataset["match_date"]
            .ffill()
        )

        print("✓ match_date converted successfully.")
        print(f"Data Type : {self.dataset['match_date'].dtype}")

        print("\nDate Range")
        print(f"First Match : {self.dataset['match_date'].min()}")
        print(f"Last Match  : {self.dataset['match_date'].max()}")
    # ==========================================================
    # STEP 12: Sort Dataset by Match Date
    # ==========================================================

    def sort_dataset_by_date(self) -> None:
        """
        Sort the dataset chronologically by match_date.
        """

        print("\n" + "=" * 70)
        print("SORT DATASET BY MATCH DATE")
        print("=" * 70)

        # Sort matches in chronological order
        self.dataset = (
            self.dataset
            .sort_values(by="match_date")
            .reset_index(drop=True)
        )

        print("✓ Dataset sorted successfully.")

        print("\nFirst 5 Match Dates")
        print(self.dataset["match_date"].head())

        print("\nLast 5 Match Dates")
        print(self.dataset["match_date"].tail())

    # ==========================================================
    # STEP 13: Create Target Variable
    # ==========================================================

    def create_target_variable(self) -> None:
        """
        Create the target variable for machine learning.

        Target Encoding
        ---------------
        Home Win : 2
        Draw     : 1
        Away Win : 0
        """

        print("\n" + "=" * 70)
        print("CREATE TARGET VARIABLE")
        print("=" * 70)

        # Create target column
        self.dataset[self.target_column] = 1

        # Home Win
        self.dataset.loc[
            self.dataset["home_score"] > self.dataset["away_score"],
            self.target_column
        ] = 2

        # Away Win
        self.dataset.loc[
            self.dataset["home_score"] < self.dataset["away_score"],
            self.target_column
        ] = 0

        print("✓ Target column created successfully.")

        print("\nTarget Distribution")
        print(
            self.dataset[self.target_column]
            .value_counts()
            .sort_index()
        )

        print("\nTarget Labels")
        print("0 -> Away Win")
        print("1 -> Draw")
        print("2 -> Home Win")

        # ==========================================================
    # STEP 14: Detect Leakage Columns
    # ==========================================================

    def detect_leakage_columns(self) -> list[str]:
        """
        Detect columns that leak match outcomes.

        Returns
        -------
        list[str]
            Leakage column names.
        """

        print("\n" + "=" * 70)
        print("LEAKAGE COLUMN DETECTION")
        print("=" * 70)

        self.leakage_columns = [
            "home_score",
            "away_score",
        ]

        print(f"Leakage Columns Found : {len(self.leakage_columns)}\n")

        for column in self.leakage_columns:
            print(f"• {column}")

        return self.leakage_columns

        # ==========================================================
    # STEP 15: Remove Leakage Columns
    # ==========================================================

    def remove_leakage_columns(self) -> None:
        """
        Remove columns that leak the match outcome.
        """

        print("\n" + "=" * 70)
        print("REMOVE LEAKAGE COLUMNS")
        print("=" * 70)

        existing_columns = [
            column
            for column in self.leakage_columns
            if column in self.dataset.columns
        ]

        self.dataset.drop(
            columns=existing_columns,
            inplace=True,
        )

        print(f"✓ Removed {len(existing_columns)} leakage columns.")

        print("\nRemoved Columns")

        for column in existing_columns:
            print(f"• {column}")

        print(f"\nRemaining Columns : {self.dataset.shape[1]}")


        # ==========================================================
    # STEP 16: Analyze Missing Values
    # ==========================================================

    def analyze_missing_values(self) -> pd.DataFrame:
        """
        Analyze missing values after preprocessing.
        """

        print("\n" + "=" * 70)
        print("ANALYZE MISSING VALUES")
        print("=" * 70)

        missing = (
            self.dataset.isnull()
            .sum()
            .sort_values(ascending=False)
        )

        missing = missing[missing > 0]

        if missing.empty:
            print("✓ No missing values found.")
            return pd.DataFrame()

        missing_df = pd.DataFrame({
            "Missing Values": missing,
            "Percentage": (
                missing / len(self.dataset) * 100
            ).round(2)
        })

        print(missing_df)

        return missing_df

        # ==========================================================
    # STEP 17: Remove String Form Columns
    # ==========================================================

    def remove_string_form_columns(self) -> None:
        """
        Remove string-based form columns that have already been
        transformed into numerical features.
        """

        print("\n" + "=" * 70)
        print("REMOVE STRING FORM COLUMNS")
        print("=" * 70)

        existing_columns = [
            column
            for column in self.string_form_columns
            if column in self.dataset.columns
        ]

        self.dataset.drop(
            columns=existing_columns,
            inplace=True,
        )

        print(f"✓ Removed {len(existing_columns)} string columns.\n")

        print("Removed Columns")

        for column in existing_columns:
            print(f"• {column}")

        print(f"\nRemaining Columns : {self.dataset.shape[1]}")


        # ==========================================================
    # STEP 17: Remove Object Columns
    # ==========================================================

    def remove_object_columns(self) -> None:
        """
        Remove all remaining object columns.

        The machine learning model requires numerical features,
        and the remaining object columns are string-based football
        form representations that already have engineered numeric
        equivalents.
        """

        print("\n" + "=" * 70)
        print("REMOVE OBJECT COLUMNS")
        print("=" * 70)

        object_columns = self.dataset.select_dtypes(
            include=["object", "string"]
        ).columns.tolist()

        if not object_columns:
            print("✓ No object columns found.")
            return

        self.dataset.drop(
            columns=object_columns,
            inplace=True,
        )

        print(f"✓ Removed {len(object_columns)} object columns.\n")

        print("Removed Columns")
        for column in object_columns:
            print(f"• {column}")

        print(f"\nRemaining Columns : {self.dataset.shape[1]}")

        # ==========================================================
    # STEP 18: Chronological Train / Validation / Test Split
    # ==========================================================

    def split_dataset(self) -> None:
        """
        Split the dataset chronologically into
        training, validation, and test datasets.
        """

        print("\n" + "=" * 70)
        print("SPLIT DATASET")
        print("=" * 70)

        total_rows = len(self.dataset)

        train_end = int(total_rows * self.train_ratio)
        validation_end = train_end + int(total_rows * self.validation_ratio)

        # Chronological split
        self.train_dataset = self.dataset.iloc[:train_end].copy()

        self.validation_dataset = self.dataset.iloc[
            train_end:validation_end
        ].copy()

        self.test_dataset = self.dataset.iloc[
            validation_end:
        ].copy()

        print("✓ Dataset split successfully.\n")

        print(f"Total Rows      : {total_rows}")
        print(f"Training Rows   : {len(self.train_dataset)}")
        print(f"Validation Rows : {len(self.validation_dataset)}")
        print(f"Test Rows       : {len(self.test_dataset)}")

        print("\nDate Ranges")
        print(
            f"Train      : "
            f"{self.train_dataset['match_date'].min()} "
            f"-> "
            f"{self.train_dataset['match_date'].max()}"
        )

        print(
            f"Validation : "
            f"{self.validation_dataset['match_date'].min()} "
            f"-> "
            f"{self.validation_dataset['match_date'].max()}"
        )

        print(
            f"Test       : "
            f"{self.test_dataset['match_date'].min()} "
            f"-> "
            f"{self.test_dataset['match_date'].max()}"
        )

        # ==========================================================
    # STEP 19: Save Dataset Splits
    # ==========================================================

    def save_datasets(self) -> None:
        """
        Save the train, validation, and test datasets.
        """

        print("\n" + "=" * 70)
        print("SAVE DATASETS")
        print("=" * 70)

        train_path = self.splits_path / "train.csv"
        validation_path = self.splits_path / "validation.csv"
        test_path = self.splits_path / "test.csv"

        self.train_dataset.to_csv(
            train_path,
            index=False,
        )

        self.validation_dataset.to_csv(
            validation_path,
            index=False,
        )

        self.test_dataset.to_csv(
            test_path,
            index=False,
        )

        print("✓ Datasets saved successfully.\n")

        print(f"Train      : {train_path}")
        print(f"Validation : {validation_path}")
        print(f"Test       : {test_path}")


    
    # ==========================================================
    # DATASET INSPECTION
    # ==========================================================

    def inspect_dataset(self) -> None:
        """
        Run all dataset inspection methods.
        """

        self.display_shape()
        self.display_columns()
        self.display_data_types()
        self.display_memory_usage()
        self.display_sample_rows()
        self.display_missing_values()
        self.display_duplicate_rows()
        self.display_numerical_summary()
        self.display_feature_type_summary()

    # ==========================================================
    # RUN DATA PREPARATION
    # ==========================================================

    def run(self) -> None:

        self.load_dataset()

        self.inspect_dataset()

        self.convert_match_date()

        self.sort_dataset_by_date()

        # Target already exists in DatasetBuilder
        self.detect_leakage_columns()

        self.remove_leakage_columns()

        self.analyze_missing_values()

        self.remove_object_columns()

        self.analyze_missing_values()

        self.split_dataset()

        self.save_datasets()
if __name__ == "__main__":
    data_preparation = DataPreparation()
    data_preparation.run()